import random


# ------------------------------------------------------------
# 1. Расширенный алгоритм Евклида (итеративная версия)
# ------------------------------------------------------------
def egcd(a, b):
    """
    Итеративный расширенный алгоритм Евклида для a, b >= 0.
    Возвращает (g, x, y), где a*x + b*y = g = НОД(a, b).
    """
    old_r, r = a, b
    old_s, s = 1, 0
    old_t, t = 0, 1

    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t

    return old_r, old_s, old_t


def egcd_v_only(a, b):
    """
    Оптимизированный вариант (пункт в): вычисляет только v
    (коэффициент при b), не отслеживая s/u.
    Возвращает (g, v), где a*u + b*v = g для некоторого u.

    Экономия: в цикле выполняется на одну серию операций меньше
    (только обновление t), что сокращает число операций примерно в 1.5 раза.
    """
    old_r, r = a, b
    old_t, t = 0, 1

    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_t, t = t, old_t - q * t

    return old_r, old_t


# ------------------------------------------------------------
# 2. Обёртки для работы с отрицательными числами
# ------------------------------------------------------------
def extended_gcd_signed(f, g):
    """Возвращает (d, u, v), где f*u + g*v = d = НОД(|f|, |g|)."""
    if f == 0 and g == 0:
        raise ValueError("f и g не могут быть одновременно нулями")

    if f == 0:
        return abs(g), 0, (1 if g > 0 else -1)
    if g == 0:
        return abs(f), (1 if f > 0 else -1), 0

    a, b = abs(f), abs(g)
    d, x, y = egcd(a, b)

    u = x if f > 0 else -x
    v = y if g > 0 else -y
    return d, u, v


def extended_gcd_signed_optimized(f, g):
    """
    Усовершенствованная версия (пункт в).
    Возвращает (d, u, v), где f*u + g*v = d = НОД(|f|, |g|),
    но использует egcd_v_only — экономит ~1.5 раза операций.
    """
    if f == 0 and g == 0:
        raise ValueError("f и g не могут быть одновременно нулями")

    if f == 0:
        return abs(g), 0, (1 if g > 0 else -1)
    if g == 0:
        return abs(f), (1 if f > 0 else -1), 0

    a, b = abs(f), abs(g)
    d, y = egcd_v_only(a, b)          # нашли только y (коэффициент при b)
    # Корректируем знаки (a = |f|, b = |g|)
    # d = a*x + b*y, значит f*(±x) + g*(±y) = d
    v = y if g > 0 else -y
    u = (d - g * v) // f              # ключевая формула из пункта в)
    return d, u, v


# ------------------------------------------------------------
# 3. Решения пунктов а, б, в
# ------------------------------------------------------------
def solve_a(f, g):
    d, u, v = extended_gcd_signed(f, g)
    print(f"\nа) f = {f}, g = {g}")
    print(f"   НОД(|f|, |g|) = {d}")
    print(f"   f*u + g*v = {f}*({u}) + {g}*({v}) = {f*u + g*v}")
    return d, u, v


def solve_b(k, l, m):
    d, u, v = extended_gcd_signed(k, l)
    print(f"\nб) k = {k}, l = {l}, m = {m}")
    print(f"   НОД(|k|, |l|) = {d}")

    if m % d != 0:
        print(f"   Решения нет: {m} не делится на {d}.")
        return None

    factor = m // d
    x, y = u * factor, v * factor
    print(f"   Частное решение: x = {x}, y = {y}")
    print(f"   Проверка: {k}*({x}) + {l}*({y}) = {k*x + l*y}")
    return x, y


def solve_v(k, l, m):
    """Пункт в) — использует оптимизированный egcd."""
    d, u, v = extended_gcd_signed_optimized(k, l)
    print(f"\nв) k = {k}, l = {l}, m = {m}")
    print(f"   НОД(|k|, |l|) = {d} (вычислен оптимизированно)")

    if m % d != 0:
        print(f"   Решения нет: {m} не делится на {d}.")
        return None

    factor = m // d
    x, y = u * factor, v * factor
    print(f"   v (коэффициент при l) = {v}  →  y = {y}")
    print(f"   u вычислен по формуле u = (d - l*v) / k")
    print(f"   Частное решение: x = {x}, y = {y}")
    print(f"   Проверка: {k}*({x}) + {l}*({y}) = {k*x + l*y}")
    return x, y


