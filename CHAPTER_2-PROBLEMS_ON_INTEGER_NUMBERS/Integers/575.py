# ------------------------------------------------------------
# 1. Разложение в цепную дробь через алгоритм Евклида
# ------------------------------------------------------------
def continued_fraction(s, t):
    """
    Возвращает список [b1, b2, ..., bk] — коэффициенты цепной дроби s/t.
    Предполагается 0 < s < t.
    """
    b_list = []
    while s != 0:
        a = t // s      # неполное частное
        r = t % s       # остаток
        b_list.append(a)
        t, s = s, r
    return b_list


# ------------------------------------------------------------
# 2. Вычисление подходящих дробей (по рекуррентным формулам)
# ------------------------------------------------------------
def convergents(s, t):
    """
    Возвращает список подходящих дробей (p_i, q_i) для s/t в порядке
    возрастания i = 1, ..., k-1 (сама дробь s/t не входит).
    Рекуррентные формулы:
      p1 = 1,               q1 = b1
      p2 = b2,              q2 = b1 * b2 + 1
      pn = bn * pn - 1 + pn - 2,  qn = bn * qn - 1 + qn - 2   (n >= 3)
    """
    b = continued_fraction(s, t)
    k = len(b)
    if k <= 1:
        return []

    result = []
    # «Нулевые» значения до начала рекурсии
    p_prev2, q_prev2 = 0, 1     # p0 / q0 = 0 / 1
    p_prev1, q_prev1 = 1, b[0]  # p1 / q1 = 1 / b1
    result.append((p_prev1, q_prev1))

    for n in range(2, k):       # n = 2, 3, ..., k-1
        pn = b[n - 1] * p_prev1 + p_prev2
        qn = b[n - 1] * q_prev1 + q_prev2
        result.append((pn, qn))
        p_prev2, q_prev2 = p_prev1, q_prev1
        p_prev1, q_prev1 = pn, qn

    return result


