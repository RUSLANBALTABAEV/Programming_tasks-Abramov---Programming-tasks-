def main():
    s, t, k = get_params()

    print(f"\nИсходные данные: s = {s}, t = {t}, k = {k}")
    print(f"Дробь s / t = {s}/{t} ≈ {s / t:.10f}")
    print("=" * 60)

    # 1) Разложение в цепную дробь
    b = continued_fraction(s, t)
    print(f"Цепная дробь: [{', '.join(map(str, b))}]   (длина k = {len(b)})")

    # 2) Подходящие дроби
    conv = convergents(s, t)

    print(f"\nа) Подходящие дроби числа {s}/{t}:")
    if not conv:
        print("  (нет: цепная дробь состоит из одного элемента)")
    else:
        for i, (p, q) in enumerate(conv, 1):
            value = p / q
            diff = abs(s / t - value)
            print(f"  {i}. p{i} / q{i} = {p} / {q} ≈ {value:.10f}"
                  f"   |s / t − p{i} / q{i}| = {diff:.10f}")

    print("-" * 60)

    # 3) Пункт б)
    print(f"б) Подходящие дроби с числителем и знаменателем < {k}:")
    filtered = [(p, q) for (p, q) in conv if p < k and q < k]

    if not filtered:
        print("  Таких подходящих дробей не существует.")
    else:
        p_last, q_last = filtered[-1]     # последняя по порядку
        diff = abs(s / t - p_last / q_last)

        print(f"  Найдено подходящих дробей: {len(filtered)}")
        for i, (p, q) in enumerate(filtered, 1):
            print(f"    {i}. {p} / {q}")

        print(f"\n  Последняя по порядку: {p_last}/{q_last}")
        print(f"  Модуль разности |s / t − p / q| = "
              f"|{s}/{t} − {p_last}/{q_last}| = {diff:.10f}")
        print(f"  Значение разности = {diff}")

    print("=" * 60)


