def solve_a(books):
    """Вывод названий книг заданного автора, изданных с 1960 года."""
    target = input("Введите фамилию автора: ").strip()
    found = [(title, year) for author, title, year in books
             if author.lower() == target.lower() and year >= 1960]
    print(f"\nа) Книги автора '{target}', изданные с 1960 г.:")
    if found:
        for title, year in found:
            print(f"   «{title}» ({year} г.)")
    else:
        print("   Таких книг не найдено.")


def solve_b(books):
    """Поиск книги 'Информатика' и вывод авторов/годов."""
    target_title = "Информатика"
    found = [(author, year) for author, title, year in books
             if title == target_title]
    print(f"\nб) Книги с названием «{target_title}»:")
    if found:
        for author, year in found:
            print(f"   Автор: {author}, год издания: {year}")
    else:
        print("   Таких книг не найдено.")


