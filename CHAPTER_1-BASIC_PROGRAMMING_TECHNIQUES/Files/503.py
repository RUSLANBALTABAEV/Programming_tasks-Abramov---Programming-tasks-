"""
ГЛАВА 1
ОСНОВНЫЕ ПРИЁМЫ ПРОГРАММИРОВАНИЯ
13. Файлы

503. Даны два символьных файла f1 и f2. Файл f1 содержит произвольный текст. Слова в тексте разделены пробелами и знаками препинания. Файл f2 содержит не более 40 слов, которые разделены запятыми. Эти слова образуют пары: каждое первое слово считается заменяемым, каждое второе слово - заменяющим. Найти в файле f1 все заменяемые слова и заменить их на соответствующие заменяющие.
Результат поместить в файле g.
"""


import os
import re

# ==========================================================
# 1. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ: Создание тестовых файлов
# ==========================================================

def create_file_f1():
    """Создаёт тестовый файл f1 с произвольным текстом."""
    text = (
        "Программирование на Python это интересно и полезно. "
        "Java также является популярным языком. "
        "Многие студенты изучают Python, C++ и Java в университете."
    )
    with open("f1.txt", 'w', encoding='utf-8') as f:
        f.write(text)
    print("Создан тестовый файл 'f1.txt'.")

def create_file_f2():
    """Создаёт тестовый файл f2 с парами слов через запятую (не более 40 слов)."""
    # Пары: заменяемое -> заменяющее
    pairs = [
        "Python", "Питон", 
        "Java", "Джава", 
        "университете", "вузе",
        "студенты", "учащиеся"
    ]
    text = ", ".join(pairs)
    with open("f2.txt", 'w', encoding='utf-8') as f:
        f.write(text)
    print("Создан тестовый файл 'f2.txt' с парами для замены.\n")

def ensure_files_exist():
    """Проверяет существование файлов и создаёт их при необходимости."""
    if not os.path.exists("f1.txt"):
        create_file_f1()
    if not os.path.exists("f2.txt"):
        create_file_f2()

# ==========================================================
# 2. ОСНОВНАЯ ПРОЦЕДУРА: Обработка и замена слов
# ==========================================================

def process_files():
    """
    Читает файлы f1, f2, заменяет слова в f1 согласно парам из f2
    и записывает результат в файл g.
    """
    try:
        # Шаг 1. Читаем файл f2 и строим словарь замен
        with open("f2.txt", 'r', encoding='utf-8') as f:
            raw_pairs = f.read()
            
        # Разбиваем по запятым и убираем лишние пробелы
        all_words = [w.strip() for w in raw_pairs.split(',') if w.strip()]
        
        if len(all_words) % 2 != 0:
            print("Предупреждение: В файле f2 нечётное количество слов. Последнее слово будет проигнорировано.")
            all_words = all_words[:len(all_words) - (len(all_words) % 2)]

        # Создаём словарь: {заменяемое: заменяющее}
        replace_dict = {}
        for i in range(0, len(all_words), 2):
            replace_dict[all_words[i]] = all_words[i+1]

        print(f"Загружено пар для замены: {len(replace_dict)}")
        print(f"Словарь замен: {replace_dict}\n")

        # Шаг 2. Читаем содержимое файла f1
        with open("f1.txt", 'r', encoding='utf-8') as f:
            text = f.read()

        # Шаг 3. Выполняем замену слов.
        # Используем регулярные выражения с \b (граница слова), чтобы не заменять части слов.
        for old_word, new_word in replace_dict.items():
            text = re.sub(r'\b' + re.escape(old_word) + r'\b', new_word, text)

        # Шаг 4. Записываем результат в файл g
        with open("g.txt", 'w', encoding='utf-8') as f:
            f.write(text)

        print(f"Результат успешно записан в файл 'g.txt'.")

    except FileNotFoundError:
        print("Ошибка: Исходные файлы не найдены.")
    except Exception as e:
        print(f"Произошла ошибка: {e}")

# ==========================================================
# 3. ОСНОВНАЯ ПРОГРАММА
# ==========================================================
def main():
    print("=== ЗАДАЧА 503: Замена слов в тексте согласно словарю ===\n")
    
    # 1. Убеждаемся, что входные файлы существуют
    ensure_files_exist()

    # 2. Выводим исходное содержимое
    print("--- Исходное содержимое 'f1.txt' ---")
    with open("f1.txt", 'r', encoding='utf-8') as f:
        print(f.read().strip())

    print("\n--- Исходное содержимое 'f2.txt' ---")
    with open("f2.txt", 'r', encoding='utf-8') as f:
        print(f.read().strip())
        
    print("\n--- Выполнение замены ---")
    
    # 3. Запускаем обработку
    process_files()

    # 4. Проверяем результат
    print("\n--- Содержимое итогового файла 'g.txt' ---")
    with open("g.txt", 'r', encoding='utf-8') as f:
        print(f.read().strip())

if __name__ == "__main__":
    main()
    input("\nНажмите Enter, чтобы завершить программу.")