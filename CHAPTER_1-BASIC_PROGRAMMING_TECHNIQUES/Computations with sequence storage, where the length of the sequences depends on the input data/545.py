import random


def get_data():
    """Выбор способа ввода исходных данных."""
    print("Задача 545: «Считалка» (задача Иосифа Флавия)")
    print("Выберите способ ввода:")
    print("1 — Ручной ввод")
    print("2 — Случайная генерация")
    print("3 — Готовые примеры")

    while True:
        choice = input("Ваш выбор (1/2/3): ").strip()
        if choice in ('1', '2', '3'):
            break
        print("Ошибка: выберите 1, 2 или 3.")

    if choice == '1':
        while True:
            try:
                n = int(input("Введите количество человек n (>=1): "))
                if n <= 0:
                    print("n должно быть положительным.")
                    continue
                m = int(input("Введите шаг счёта m (>=1): "))
                if m <= 0:
                    print("m должно быть положительным.")
                    continue
                return n, m
            except ValueError:
                print("Ошибка ввода. Повторите.")

    elif choice == '2':
        n = random.randint(1, 10)
        # m может быть любым натуральным, но для наглядности ограничим 1..10
        m = random.randint(1, 10)
        print(f"\nСгенерированы случайные данные: n = {n}, m = {m}")
        return n, m

    else:  # готовые примеры
        examples = [
            (5, 2),   # классический пример, ответ 3
            (7, 3),   # ответ 4
            (1, 1),   # единственный человек
            (10, 4),  # ответ 5
        ]
        print("\nГотовые примеры:")
        for idx, (n_val, m_val) in enumerate(examples, 1):
            print(f"{idx}: n = {n_val}, m = {m_val}")
        while True:
            try:
                num = int(input("Выберите номер примера: "))
                if 1 <= num <= len(examples):
                    return examples[num - 1]
                else:
                    print(f"Номер должен быть от 1 до {len(examples)}.")
            except ValueError:
                print("Ошибка ввода. Введите целое число.")


def solve_josephus(n, m):
    """
    Решение задачи Иосифа Флавия с помощью стандартного списка.
    Возвращает номер последнего оставшегося человека.
    """
    people = list(range(1, n + 1))
    idx = 0
    while len(people) > 1:
        idx = (idx + m - 1) % len(people)
        people.pop(idx)
    return people[0]


def main():
    n, m = get_data()

    # Вычисляем номер последнего оставшегося
    survivor = solve_josephus(n, m)

    # Вывод результатов
    print("\nРезультаты:")
    print(f"Исходные данные: n = {n}, m = {m}")
    print(f"Последний оставшийся в круге человек имеет номер: {survivor}")


if __name__ == "__main__":
    main()
