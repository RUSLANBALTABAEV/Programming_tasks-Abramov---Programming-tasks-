# а) Решение задачи 531 с использованием массива (n <= 1000)
# ==========================================================
def solve_531_array():
    print("\n=== ЗАДАЧА 531 (массив) ===")
    MAX_N = 1000
    
    n = int(input(f"Введите количество чисел n (2 <= n <= {MAX_N}): "))
    if n < 2 or n > MAX_N:
        print(f"Ошибка: n должно быть в диапазоне от 2 до {MAX_N}.")
        return

    # Создаем фиксированный массив размером MAX_N и заполняем его нулями
    a = [0.0] * MAX_N
    print(f"Введите {n} действительных чисел через пробел:")
    input_data = list(map(float, input().split()))
    
    if len(input_data) != n:
        print(f"Ошибка: введено {len(input_data)} чисел, а ожидается {n}.")
        return
        
    # Заносим данные в массив (используем только первые n ячеек)
    for i in range(n):
        a[i] = input_data[i]

    xn = a[n-1]  # Последний элемент массива

    # Формируем результат (тоже в виде массива с запасом)
    result = [0.0] * (n - 1)
    print(f"\nПоследний элемент (xn) = {xn}")
    print("Результат (xi - xn):", end=" ")
    for i in range(n - 1):
        result[i] = a[i] - xn
        print(f"{result[i]:.4f}", end=" ")
    print()


