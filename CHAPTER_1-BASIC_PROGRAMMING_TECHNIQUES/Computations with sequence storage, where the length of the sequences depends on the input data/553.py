# б) Решение задачи 532 с использованием массива (n <= 1500)
# ==========================================================
def solve_532_array():
    print("\n=== ЗАДАЧА 532 (массив) ===")
    MAX_N = 1500
    
    n = int(input(f"Введите количество чисел n (1 <= n <= {MAX_N}): "))
    if n < 1 or n > MAX_N:
        print(f"Ошибка: n должно быть в диапазоне от 1 до {MAX_N}.")
        return

    # Создаем фиксированный массив
    a = [0.0] * MAX_N
    print(f"Введите {n} действительных чисел через пробел:")
    input_data = list(map(float, input().split()))
    
    if len(input_data) != n:
        print(f"Ошибка: введено {len(input_data)} чисел, а ожидается {n}.")
        return
        
    for i in range(n):
        a[i] = input_data[i]

    # Проверяем, упорядочена ли последовательность по неубыванию
    is_sorted = True
    for i in range(n - 1):
        if a[i] > a[i+1]:
            is_sorted = False
            break

    print(f"\nИсходная последовательность: {a[:n]}")
    print(f"Упорядочена по неубыванию: {'Да' if is_sorted else 'Нет'}")

    # Выводим результат в зависимости от условия
    if is_sorted:
        print(f"Результат (без изменений): {a[:n]}")
    else:
        # Создаем массив для обратной последовательности
        reversed_a = [0.0] * n
        for i in range(n):
            reversed_a[i] = a[n - 1 - i]
        print(f"Результат (обратный порядок): {reversed_a}")


